def generate(out_root: Path, *, small: bool, only: set[str] | None, offline: bool, log=print) -> list[Path]:
    ctx = Context(offline)
    root = out_root / "small" if small else out_root
    written: list[Path] = []
    all_items = items(small)
    want = set(only) if only else None
    if want:                                   # a dropped-pages item needs its base item's GT
        for it in all_items:
            if it.name in want and it.build == "dropped":
                want.add(it.params["base"])
    gts: dict[str, dict] = {}
    for it in all_items:
        if want is not None and it.name not in want:
            continue
        t0 = time.time()
        seed = seed_of(it.name)
        d = root / it.name
        if it.build == "dropped":
            base = gts.get(it.params["base"]) or json.loads((root / it.params["base"] / "gt.json").read_text("utf-8"))
            gt = build_dropped(ctx, it, seed, d, base)
        else:
            doc, pages, ids, extra = BUILDERS[it.build](ctx, it, seed)
            if len(pages) != it.pages:
                raise RuntimeError(f"{it.name}: laid out {len(pages)} pages, wanted {it.pages}")
            save(doc, d / f"{it.name}.pdf")
            gt = _gt(it, pages, ids, seed=seed, extra=extra, font_sha=ctx.font_sha)
        gts[it.name] = gt
        d.mkdir(parents=True, exist_ok=True)
        (d / "gt.json").write_text(json.dumps(gt, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
                                   encoding="utf-8", newline="\n")
        written.append(d)
        log(f"{it.name}: {gt['pages']} pages in {time.time() - t0:.1f}s")
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--small", action="store_true", help="one item per category, 3 pages each, into <out>/small/")
    ap.add_argument("--only", help="comma-separated item names")
    ap.add_argument("--out", default=str(HERE), help="corpus root (default bench/corpus)")
    ap.add_argument("--offline", action="store_true", help="never download; fail when a pinned source is missing")
    ap.add_argument("--seed-salt", default="", help="prefix every item seed: a fresh corpus (write it to its own --out)")
    a = ap.parse_args(argv)
    global SEED_SALT
    SEED_SALT = a.seed_salt
    t0 = time.time()
    try:
        generate(Path(a.out), small=a.small, only=set(a.only.split(",")) if a.only else None, offline=a.offline)
    except sources.SourceError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    print(f"done in {time.time() - t0:.1f}s")
    return 0


