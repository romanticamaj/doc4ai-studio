_ZH_HEADING = re.compile(r"^第[一二三四五六七八九十百千零〇\d]+回")
_EN_HEADING = re.compile(r"^(CHAPTER|Chapter)\s+[IVXLC\d]+\.?")
_DASHES = re.compile(r"^[-—=*\s]+$")


@dataclass
class Para:
    kind: str                          # "h" heading | "p" paragraph | "code" code line
    text: str


def zh_paragraphs(key: str, cmap: set[int], *, offline: bool) -> list[Para]:
    """Headings (第N回) and paragraphs; wrapped lines are joined (a line shorter than the wrap width ends one)."""
    out: list[Para] = []
    buf: list[str] = []

    def flush():
        if buf:
            t = "".join(buf)
            if t:
                out.append(Para("p", t))
            buf.clear()
    raw_lines = sources.text_body(key, offline=offline).split("\n")
    widths = sorted(len(r.strip()) for r in raw_lines if len(r.strip()) > 8)
    wrap = widths[int(len(widths) * 0.9)] if widths else 30       # the book's hard-wrap width
    for raw in raw_lines:
        line = raw.strip().replace("　", "")
        line = "".join(c for c in line if ord(c) in cmap)
        if not line or _DASHES.match(line):
            flush()
            continue
        if _ZH_HEADING.match(line):
            flush()
            out.append(Para("h", line))
            continue
        buf.append(line)
        # a clearly short line that ends a sentence ends its paragraph
        if len(raw.strip()) < wrap - 3 and line[-1] in "。！？」』”．!?\"":
            flush()
    flush()
    return out


def en_paragraphs(key: str, cmap: set[int], *, offline: bool) -> list[Para]:
    body = sources.text_body(key, offline=offline).replace("_", "")
    blocks = [" ".join(ln.strip() for ln in b.split("\n") if ln.strip()) for b in re.split(r"\n\s*\n", body)]
    blocks = ["".join(c for c in b if ord(c) in cmap) for b in blocks]
    start = 0
    for i, b in enumerate(blocks[:-1]):          # body starts at the first heading followed by a real paragraph
        if _EN_HEADING.match(b) and len(blocks[i + 1]) > 200:
            start = i
            break
    out: list[Para] = []
    for b in blocks[start:]:
        if not b or b.startswith("[Illustration") or _DASHES.match(b):
            continue
        out.append(Para("h" if _EN_HEADING.match(b) and len(b) < 80 else "p", b))
    return out


