def build_book(ctx: Context, item: Item, seed: int):
    """1,200 pages: table of contents, the four novels in order (each starts on a new page), 20 blank pages at
    chapter ends, two tables that run across a page break."""
    header = "四大小說合輯 · Doc4AI 1200"
    rng = random.Random(seed)
    toc_pages = item.params.get("toc_pages", 4)
    st = Setter(ctx.font, "cht", header=header)
    for _ in range(toc_pages):                 # placeholder pages, filled after the body is laid out
        st.break_page()
    chapters: list[tuple[str, int]] = []
    heads_total = sum(1 for k in ZH_BOOKS for p in ctx.paras(k) if p.kind == "h")
    blank_after = set(rng.sample(range(5, max(6, heads_total // 2)), 20))
    tables_at = set(rng.sample(range(10, max(11, heads_total // 2)), 2))
    h = 0
    for key in ZH_BOOKS:
        if st.full(item.pages):
            break
        st.break_page()
        st.para(Para("h", sources.SOURCES[key]["title"].split(" (")[0]))
        for p in ctx.paras(key):
            if st.full(item.pages):
                break
            if p.kind == "h":
                h += 1
                if h in blank_after:
                    st.blank_page()
                chapters.append((p.text, len(st.pages)))
                if h in tables_at:
                    room = int((PAGE_H - BOTTOM - st.y - 12) // 22)
                    st.table(_table(rng, 6, max(5, room + 5), merged=True), allow_split=True)
            st.para(p)
    body = st.finish(item.pages)
    # table of contents in the reserved pages (entries that fit; the TOC is text, the GT records it)
    toc = Setter(ctx.font, "cht", header=header)
    toc.para(Para("h", "目錄"))
    for title, page in chapters:
        if len(toc.pages) > toc_pages or (len(toc.pages) == toc_pages and not toc._room(toc.lh * 2)):
            break
        toc.para(Para("p", f"{title} ……… {page}"))
    toc_out = toc.finish()[:toc_pages]
    while len(toc_out) < toc_pages:
        toc_out.append(PageOut(blank=True))
    pages = toc_out + body[toc_pages:]
    pages = pages[:item.pages]
    doc = render(pages, ctx.font_path, header=header)
    return doc, pages, [sources.SOURCES[k]["gutenberg_id"] for k in ZH_BOOKS], {"toc_pages": toc_pages}


def build_dropped(ctx: Context, item: Item, seed: int, out_dir: Path, base_gt: dict) -> dict:
    """Verify's negative samples (not conversion inputs): the base item's exact text as our own Markdown, then a
    control copy, pages silently emptied, markers shifted by one, two pages moved out of order."""
    n = base_gt["pages"]
    rng = random.Random(seed)
    pt = base_gt["page_text"]
    blank = set(base_gt["blank_pages"])
    content = [p for p in range(1, n + 1) if p not in blank]

    def md(order=None, shift=0, empty=()):
        order = order or list(range(1, n + 1))
        return "".join(f"<!-- page: {p + shift} -->\n\n{'' if p in empty else pt[str(p)]}\n\n" for p in order)
    k_drop = 5 if len(content) >= 12 else 1
    dropped = sorted(rng.sample(content[1:-1] or content, k_drop))
    a = content[len(content) // 3]
    b = content[min(len(content) - 1, len(content) // 3 + 1)]
    order = list(range(1, n + 1))
    ia, ib = order.index(a), order.index(b)
    order[ia], order[ib] = order[ib], order[ia]
    # swapped_content: markers stay in order, the two pages' text is exchanged (verifier round)
    swapped_text = "".join(f"<!-- page: {p} -->\n\n{pt[str({a: b, b: a}.get(p, p))]}\n\n" for p in range(1, n + 1))
    # partial: one page cut to its first 15 % (looked like the control before page_partial existed)
    cut = max(content, key=lambda p: (len(pt[str(p)]), -p))    # a full page, not the short one before a blank
    partial = "".join(f"<!-- page: {p} -->\n\n{pt[str(p)][: max(1, len(pt[str(p)]) * 15 // 100)] if p == cut else pt[str(p)]}"
                      f"\n\n" for p in range(1, n + 1))
    files = {"control.md": md(), "dropped.md": md(empty=set(dropped)), "shifted.md": md(shift=1),
             "swapped.md": md(order=order), "swapped_content.md": swapped_text, "partial.md": partial}
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
    return {"name": item.name, "tier": "A", "gt_level": "L1", "pages": n, "lang": base_gt["lang"],
            "kind": "verify-negative", "license": base_gt["license"], "base": base_gt["name"],
            "pdf": f"../{base_gt['name']}/{base_gt['name']}.pdf", "files": sorted(files),
            "defects": {"broken_text_layer_pages": [], "dropped_pages": dropped, "marker_shift": 1,
                        "swapped_pages": [a, b], "swapped_content_pages": [a, b], "partial_pages": [cut]},
            "expected": {"control.md": {"level": "ok", "exit": 0}, "dropped.md": {"level": "warn", "exit_fail_on_warn": 1},
                         "shifted.md": {"level": "low", "exit": 1}, "swapped.md": {"level": "low", "exit": 1},
                         "swapped_content.md": {"exit_fail_on_warn": 1}, "partial.md": {"exit_fail_on_warn": 1}},
            "generator": {"script": "make_synthetic.py", "version": GENERATOR_VERSION, "seed": seed}}


