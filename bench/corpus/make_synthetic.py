def _table(rng: random.Random, n_cols: int, n_rows: int, merged: bool) -> Table:
    head = [rng.choice(ZH_WORDS) for _ in range(n_cols)]
    spans = []
    if merged and n_cols >= 4:
        c = rng.randrange(1, n_cols - 1)
        head[c] = head[c] + "合併"
        head[c + 1] = ""
        spans.append({"row": 0, "col": c, "colspan": 2})
    rows = [head]
    for _ in range(n_rows - 1):
        row = [rng.choice(ZH_WORDS[:7] + ZH_WORDS[11:])]
        row += [str(rng.randrange(10, 99999)) for _ in range(n_cols - 1)]
        rows.append(row)
    return Table(rows, spans)


def build_tables(ctx: Context, item: Item, seed: int):
    header = "表格測試 · Doc4AI tables"
    st = Setter(ctx.font, "cht", header=header)
    rng = random.Random(seed)
    paras = [p for p in ctx.stream(ZH_BOOKS[2:3], seed) if p.kind == "p" and len(p.text) > 40]
    i = 0
    cross_done = False
    while not st.full(item.pages):
        st.para(Para("p", paras[i % len(paras)].text[:160]))
        i += 1
        for _ in range(rng.randint(1, 3)):
            n_cols = rng.randint(3, 8)
            st.table(_table(rng, n_cols, rng.randint(4, 7), merged=True), allow_split=False)
        if not cross_done and len(st.pages) >= max(1, item.pages // 2) and item.pages >= 2:
            # one table that runs across a page break: fill the page, then split the rows
            st.para(Para("p", paras[i % len(paras)].text[:120]))
            room = int((PAGE_H - BOTTOM - st.y - 12) // 22)
            st.table(_table(rng, 5, max(4, room + 4), merged=False), allow_split=True)
            cross_done = True
        if not cross_done or rng.random() < 0.5:
            st.break_page()
    pages = st.finish(item.pages)
    doc = render(pages, ctx.font_path, header=header)
    return doc, pages, [sources.SOURCES["pg23962"]["gutenberg_id"]], None


