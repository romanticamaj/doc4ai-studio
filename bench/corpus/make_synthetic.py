@dataclass
class Table:
    cells: list[list[str]]
    spans: list[dict] = field(default_factory=list)      # [{"row", "col", "colspan"}]


@dataclass
class PageOut:
    lines: list[tuple[float, float, str, float, str]] = field(default_factory=list)   # x, y, text, size, font key
    shapes: list[tuple] = field(default_factory=list)                                # ("line", p0, p1) / ("rect", r)
    images: list[tuple] = field(default_factory=list)                                # (rect, png bytes)
    text: list[str] = field(default_factory=list)        # GT body pieces in reading order
    tables: list[dict] = field(default_factory=list)
    formulas: list[str] = field(default_factory=list)
    blank: bool = False
    broken: bool = False                                 # body text in the broken (no ToUnicode) font


class Setter:
    """Flows paragraphs into A4 pages with a measured font; records the exact text of every page."""

    def __init__(self, font: fitz.Font, lang: str, *, header: str | None, body_size: float | None = None,
                 col_count: int = 1):
        self.font, self.lang, self.header = font, lang, header
        self.size = body_size or (12.0 if lang == "cht" else 11.0)
        self.lh = self.size * 1.6
        self.cols = col_count
        self.gap = 24.0
        self.col_w = (PAGE_W - 2 * MARGIN_X - (col_count - 1) * self.gap) / col_count
        self.pages: list[PageOut] = []
        self._w: dict[str, float] = {}
        self._new_page()

    # -- measurement
    def width(self, s: str, size: float) -> float:
        if self.lang == "cht" or len(s) <= 1:
            total = 0.0
            for c in s:
                w = self._w.get(c)
                if w is None:
                    w = self._w[c] = self.font.text_length(c, 1.0)
                total += w
            return total * size
        return self.font.text_length(s, size)

    def wrap(self, text: str, size: float, width: float) -> list[str]:
        lines: list[str] = []
        if self.lang == "cht":
            cur, w = [], 0.0
            for c in text:
                cw = self.width(c, size)
                if cur and w + cw > width:
                    lines.append("".join(cur))
                    cur, w = [], 0.0
                cur.append(c)
                w += cw
            if cur:
                lines.append("".join(cur))
            return lines
        cur_s = ""
        for word in text.split(" "):
            cand = word if not cur_s else cur_s + " " + word
            if cur_s and self.font.text_length(cand, size) > width:
                lines.append(cur_s)
                cur_s = word
            else:
                cur_s = cand
        if cur_s:
            lines.append(cur_s)
        return lines

    # -- pages
    @property
    def page(self) -> PageOut:
        return self.pages[-1]

    def _new_page(self) -> None:
        self.pages.append(PageOut())
        self.col = 0
        self.y = TOP

    def break_page(self) -> None:
        self._new_page()

    def blank_page(self) -> None:
        if self.page.lines or self.page.shapes or self.page.images:
            self._new_page()
        self.page.blank = True
        self._new_page()

    def _x(self) -> float:
        return MARGIN_X + self.col * (self.col_w + self.gap)

    def _advance_column(self) -> None:
        if self.col + 1 < self.cols:
            self.col += 1
            self.y = TOP
        else:
            self._new_page()

    def _room(self, h: float) -> bool:
        return self.y + h <= PAGE_H - BOTTOM

    def para(self, p: Para, joiner: str | None = None) -> None:
        size = self.size * (1.35 if p.kind == "h" else 1.0)
        lh = size * 1.6
        if p.kind == "h" and not self._room(lh * 3):
            self._advance_column()
        joiner = joiner if joiner is not None else ("" if self.lang == "cht" else " ")
        piece: list[str] = []
        for line in self.wrap(p.text, size, self.col_w):
            if not self._room(lh):
                if piece:
                    self.page.text.append(joiner.join(piece))
                    piece = []
                self._advance_column()
            self.y += lh
            self.page.lines.append((self._x(), self.y - lh * 0.3, line, size, "body"))
            piece.append(line)
        if piece:
            self.page.text.append(joiner.join(piece))
        self.y += self.lh * (0.6 if p.kind == "p" else 0.4)

    def table(self, t: Table, row_h: float = 22.0, *, allow_split: bool = True) -> None:
        size = 9.5
        n_cols = len(t.cells[0])
        w = self.col_w
        if not self._room(row_h * 2 + 8):
            self._advance_column()
        rows = list(range(len(t.cells)))
        first = True
        while rows:
            fit = int((PAGE_H - BOTTOM - self.y - 8) // row_h)
            take = rows[:fit] if allow_split else rows
            if not take or (not allow_split and len(take) < len(rows)):
                self._advance_column()
                continue
            y0 = self.y + 4
            x0 = self._x()
            part = [t.cells[r] for r in take]
            spans = [{**s, "row": s["row"] - take[0]} for s in t.spans if s["row"] in take]
            covered = {(s["row"], s["col"] + k) for s in spans for k in range(1, s["colspan"])}
            for i in range(len(take) + 1):
                self.page.shapes.append(("line", (x0, y0 + i * row_h), (x0 + w, y0 + i * row_h)))
            for c in range(n_cols + 1):
                cx = x0 + c * w / n_cols
                for i in range(len(take)):
                    if (i, c) in covered:              # no rule inside a merged cell
                        continue
                    self.page.shapes.append(("line", (cx, y0 + i * row_h), (cx, y0 + (i + 1) * row_h)))
            text_rows = []
            for i, row in enumerate(part):
                vals = []
                for c, val in enumerate(row):
                    if (i, c) in covered:
                        continue
                    if val:
                        self.page.lines.append((x0 + c * w / n_cols + 4, y0 + i * row_h + row_h * 0.68, val, size,
                                                "body"))
                    vals.append(val)
                text_rows.append(" ".join(v for v in vals if v))
            self.page.text.append("\n".join(text_rows))
            self.page.tables.append({"cells": part, "n_cols": n_cols, "spans": spans,
                                     "spans_pages": len(take) < len(t.cells)})
            self.y = y0 + len(take) * row_h + 10
            rows = rows[len(take):]
            if rows:
                first = False
                self._advance_column()
        del first

    def formula(self, latex: str, png: bytes, w: float, h: float) -> None:
        if not self._room(h + 10):
            self._advance_column()
        x = self._x() + (self.col_w - w) / 2
        self.page.images.append((fitz.Rect(x, self.y + 4, x + w, self.y + 4 + h), png))
        self.page.formulas.append(latex)
        self.y += h + 12

    def figure(self, caption: str) -> None:
        h = 90.0
        if not self._room(h + self.lh * 3):
            self._advance_column()
        x = self._x()
        self.page.shapes.append(("rect", fitz.Rect(x + 10, self.y + 4, x + self.col_w - 10, self.y + 4 + h)))
        self.y += h + 8
        self.para(Para("p", caption))

    def finish(self, pages: int | None = None) -> list[PageOut]:
        while self.pages and not (self.page.lines or self.page.shapes or self.page.images or self.page.blank):
            self.pages.pop()
        if pages is not None:
            self.pages = self.pages[:pages]
        return self.pages

    def full(self, pages: int) -> bool:
        return len(self.pages) > pages


