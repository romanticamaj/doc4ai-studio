def subset_font(full_path: Path, chars: set[str]) -> bytes:
    """The used glyphs of the OFL font as a small TrueType font. The CID-keyed CFF of Noto CJK cannot be subset
    for embedding as is (MuPDF maps CIDs to glyphs by the original numbering), so the outlines are converted to
    quadratic curves (fontTools' otf2ttf recipe)."""
    from fontTools import subset
    from fontTools.pens.cu2quPen import Cu2QuPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    from fontTools.ttLib import TTFont, newTable
    f = TTFont(str(full_path))
    opts = subset.Options()
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.layout_features = []
    opts.drop_tables += ["vmtx", "vhea", "VORG", "GSUB", "GPOS", "BASE", "DSIG"]   # horizontal text only
    s = subset.Subsetter(opts)
    s.populate(unicodes={ord(c) for c in chars} | set(range(0x20, 0x7F)))
    s.subset(f)
    order = f.getGlyphOrder()
    gs = f.getGlyphSet()
    glyphs = {}
    for name in order:
        pen = TTGlyphPen(None)
        gs[name].draw(Cu2QuPen(pen, max_err=1.0, reverse_direction=True))
        glyphs[name] = pen.glyph()
    f["loca"] = newTable("loca")
    f["glyf"] = glyf = newTable("glyf")
    glyf.glyphOrder = order
    glyf.glyphs = glyphs
    del f["CFF "]
    glyf.compile(f)
    hmtx = f["hmtx"]
    for name, g in glyf.glyphs.items():
        if hasattr(g, "xMin"):
            hmtx[name] = (hmtx[name][0], g.xMin)
    f["maxp"] = maxp = newTable("maxp")
    maxp.tableVersion = 0x00010000
    for k in ("maxZones",):
        setattr(maxp, k, 1)
    for k in ("maxTwilightPoints", "maxStorage", "maxFunctionDefs", "maxInstructionDefs", "maxStackElements",
              "maxSizeOfInstructions", "maxComponentElements"):
        setattr(maxp, k, 0)
    maxp.compile(f)
    post = f["post"]
    post.formatType = 2.0
    post.extraNames = []
    post.mapping = {}
    post.glyphOrder = order
    f.sfntVersion = TRUETYPE_SFNT
    b = io.BytesIO()
    f.save(b)
    return b.getvalue()


def render(pages: list[PageOut], font_path: Path, *, header: str | None, footer_broken: bool = False) -> fitz.Document:
    chars = {c for p in pages for ln in p.lines for c in ln[2]} | set(header or "") | set("0123456789")
    sub = subset_font(font_path, chars)
    broken_buf = sub + b"\0"                     # another buffer -> another font object, whose ToUnicode is removed
    doc = fitz.open()
    for n, p in enumerate(pages, 1):
        page = doc.new_page(width=PAGE_W, height=PAGE_H)
        if p.blank:
            continue
        page.insert_font(fontname="N", fontbuffer=sub)
        body = "N"
        if p.broken or footer_broken:
            page.insert_font(fontname="B", fontbuffer=broken_buf)
            body = "B" if p.broken else "N"
        if header:
            page.insert_text((MARGIN_X, HEADER_Y), header, fontname="N", fontsize=9)
            page.insert_text((PAGE_W / 2 - 6, FOOTER_Y), str(n), fontname="B" if footer_broken else "N", fontsize=9)
        if p.shapes:
            sh = page.new_shape()
            for s in p.shapes:
                if s[0] == "line":
                    sh.draw_line(s[1], s[2])
                else:
                    sh.draw_rect(s[1])
            sh.finish(width=0.8, color=(0, 0, 0), fill=None)
            sh.commit()
        for x, y, text, size, _ in p.lines:
            page.insert_text((x, y), text, fontname=body, fontsize=size)
        for rect, png in p.images:
            page.insert_image(rect, stream=png)
    for xref in range(1, doc.xref_length()):        # embedded font programs are stored raw: deflate them
        try:
            if doc.xref_get_key(xref, "Subtype")[1] == "/OpenType" and doc.xref_is_stream(xref):
                doc.update_stream(xref, doc.xref_stream(xref), compress=True)
        except Exception:  # noqa: BLE001, S112  non-dict objects
            continue
    for page in doc:
        for f in page.get_fonts():
            if f[4] == "B":
                doc.xref_set_key(f[0], "ToUnicode", "null")
    doc.set_metadata({"producer": "doc4ai bench make_synthetic", "creator": "doc4ai bench",
                      "creationDate": "D:20261005000000Z", "modDate": "D:20261005000000Z"})
    return doc


def save(doc: fitz.Document, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path, garbage=4, deflate=True, no_new_id=True)
    doc.close()


def math_png(latex: str) -> tuple[bytes, float, float]:
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import mathtext
    buf = io.BytesIO()
    mathtext.math_to_image(f"${latex}$", buf, dpi=200, format="png")
    png = buf.getvalue()
    pix = fitz.Pixmap(png)
    return png, pix.width * 72 / 200, pix.height * 72 / 200


# ---------------------------------------------------------------- scans (Pillow + numpy, seeded)

def degrade(img, kind: str, rng: random.Random):
    import numpy as np
    from PIL import Image, ImageDraw, ImageFilter
    img = img.convert("L")
    if kind == "noise":
        arr = np.asarray(img).astype(np.int16)
        noise = np.random.default_rng(rng.randrange(2 ** 32)).normal(0, 22, arr.shape)
        img = Image.fromarray(np.clip(arr + noise, 0, 255).astype(np.uint8))
    elif kind == "skew":
        img = img.rotate(rng.uniform(-1.5, 1.5), resample=Image.BICUBIC, fillcolor=255)
    elif kind == "bleed":
        img = img.filter(ImageFilter.GaussianBlur(1.1)).point(lambda v: 0 if v < 170 else v)
    elif kind == "fold":
        d = ImageDraw.Draw(img)
        x = int(img.width * rng.uniform(0.35, 0.65))
        for k in range(18):
            d.line([(x + k, 0), (x + k, img.height)], fill=170 + k * 4)
    return img


def scan_pdf(text_doc: fitz.Document, kinds: list[str], seed: int, dpi: int = 200,
             quality: int = 80) -> fitz.Document:
    from PIL import Image
    rng = random.Random(seed)
    out = fitz.open()
    for i, page in enumerate(text_doc):
        new = out.new_page(width=page.rect.width, height=page.rect.height)
        pix = page.get_pixmap(dpi=dpi, colorspace=fitz.csGRAY)
        if not page.get_text().strip() and not page.get_drawings() and not page.get_images():
            continue                                  # blank page stays blank
        img = Image.frombytes("L", (pix.width, pix.height), pix.samples)
        kind = kinds[i % len(kinds)]
        img = degrade(img, kind, rng)
        b = io.BytesIO()
        img.save(b, format="JPEG", quality=55 if kind == "jpeg" else quality)
        new.insert_image(new.rect, stream=b.getvalue())
    out.set_metadata({"producer": "doc4ai bench make_synthetic (scan)", "creationDate": "D:20261005000000Z",
                      "modDate": "D:20261005000000Z"})
    return out


