"""Calibration of the scan-page checks (aidoc.scanchecks, ticket T-002). Not part of the package.

    uv run python bench/scan_calib.py [--out bench/results/scan-calib.json] [--labels]

Design set (thresholds are set here, then frozen):
- the synthetic Tier A scans (bench/corpus/syn-scan-*, regenerated by bench/corpus/make_synthetic.py) with their
  page-aligned GT: a faithful conversion (= the GT) must raise nothing (false positives), and simulated faults must
  be flagged on the right pages (recall):
    empty      — page p's section is empty;
    moved      — page p+1's text under page p, page p+1 empty;
    cut        — page p+1 cut to its first 1/8, the rest under page p;
    two_in_one — pages p+1 and p+2 under page p, both empty;
- `--labels`: the design label pages (tests/fixtures/page_labels.json, private samples) — every page the scan checks
  judge (no text layer) and what they raise, against the label verdicts.

The real-sample regression set (tests/fixtures/manual/realeval) is reported separately, once, as information
(`--realeval <run>`): it never sets a threshold."""
from __future__ import annotations

import argparse
import itertools
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aidoc import scanchecks as S

CORPUS = ROOT / "bench" / "corpus"


def _md(secs: dict[int, str]) -> str:
    return "".join(f"<!-- page: {p} -->\n{t}\n\n" for p, t in sorted(secs.items()))


def _flags(md: str, ink, blank) -> dict[int, list[str]]:
    return {e["page"]: e["reasons"] for e in S.scan_page_checks(md, ink, blank)}


def synthetic(docs: list[Path]) -> dict:
    tot = {"pages": 0, "fp_pages": 0, "clean_docs_flagged": 0, "docs": 0}
    sc = {k: {"cases": 0, "hit": 0, "exact": 0, "extra_flags": 0} for k in ("empty", "moved", "cut", "two_in_one")}
    per_doc = {}
    for gt_path in docs:
        gt = json.loads(gt_path.read_text(encoding="utf-8"))
        pdf = gt_path.parent / f"{gt_path.parent.name}.pdf"
        if not pdf.is_file():
            continue
        ink = S.page_ink(pdf)
        blank = set(gt.get("blank_pages") or [])
        pages = {int(k): v for k, v in gt["page_text"].items()}
        n = int(gt["pages"])
        content = [p for p in range(1, n + 1) if p not in blank and S.section_chars(pages.get(p, "")) >= 20]
        clean = _flags(_md(pages), ink, blank)
        tot["docs"] += 1
        tot["pages"] += len(content)
        tot["fp_pages"] += len(clean)
        tot["clean_docs_flagged"] += bool(clean)
        per_doc[gt_path.parent.name] = {"pages": len(content), "clean_flags": clean,
                                        "cells_per_char": _ratio(ink, pages, content)}

        def case(kind, secs, expect: set[int], ink=ink, blank=blank):
            got = _flags(_md(secs), ink, blank)
            sc[kind]["cases"] += 1
            sc[kind]["hit"] += expect <= set(got)
            sc[kind]["exact"] += set(got) == expect
            sc[kind]["extra_flags"] += len(set(got) - expect)
        for p in content:
            s = dict(pages)
            s[p] = ""
            case("empty", s, {p})
        for p, q in itertools.pairwise(content):
            if q != p + 1:
                continue
            s = dict(pages)
            s[p], s[q] = pages[p] + "\n" + pages[q], ""
            case("moved", s, {p, q})
            s = dict(pages)
            cut = len(pages[q]) // 8
            s[p], s[q] = pages[p] + "\n" + pages[q][cut:], pages[q][:cut]
            case("cut", s, {p, q})
        for p in content:
            if p + 1 in content and p + 2 in content:
                s = dict(pages)
                s[p], s[p + 1], s[p + 2] = pages[p] + pages[p + 1] + pages[p + 2], "", ""
                case("two_in_one", s, {p, p + 1, p + 2})
    for v in sc.values():
        v["recall"] = round(v["hit"] / v["cases"], 4) if v["cases"] else None
    tot["fp_rate"] = round(tot["fp_pages"] / tot["pages"], 4) if tot["pages"] else None
    return {"totals": tot, "scenarios": sc, "per_doc": per_doc}


def _ratio(ink, pages, content):
    vals = [S.section_chars(pages[p]) / ink[p].cells for p in content if ink.get(p) and ink[p].cells]
    vals.sort()
    return {"min": round(vals[0], 3), "median": round(vals[len(vals) // 2], 3), "max": round(vals[-1], 3)} if vals else None


def labels() -> dict:
    sys.path.insert(0, str(ROOT / "bench"))
    from bench.page_labels import MANUAL, load
    docs, rows = load()
    verdict = {(r["doc"], r["page"]): r["verdict"] for r in rows}
    out = {"docs": 0, "scan_pages_judged": 0, "flags": [], "labelled_scan_pages": 0}
    from aidoc.probe import probe_file
    for key, d in docs.items():
        pdf = MANUAL / d["pdf"]
        md = (MANUAL / d["md"]).read_text(encoding="utf-8")
        ink = S.page_ink(pdf)
        judged = [p for p, v in ink.items() if v is not None]
        out["docs"] += 1
        out["scan_pages_judged"] += len(judged)
        out["labelled_scan_pages"] += sum(1 for p in judged if (key, p) in verdict)
        for e in S.scan_page_checks(md, ink, probe_file(pdf).blank_pages):
            out["flags"].append({"doc": key, "page": e["page"], "reasons": e["reasons"],
                                 "label": verdict.get((key, e["page"]))})
    return out


def realeval(run: Path) -> dict:
    """Information only (the regression set): each run output's scan flags."""
    out = {}
    for md in sorted(run.glob("out-*/*/*.md")):
        config, doc = md.parent.parent.name[4:], md.parent.name
        pdf = run / "inputs" / f"{doc}.pdf"
        if not pdf.is_file():
            continue
        ink = S.page_ink(pdf)
        flags = S.scan_page_checks(md.read_text(encoding="utf-8"), ink)
        out[f"{config}/{doc}"] = {e["page"]: e["reasons"] for e in flags}
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out")
    ap.add_argument("--labels", action="store_true")
    ap.add_argument("--realeval", help="a realeval run folder (information only)")
    a = ap.parse_args(argv)
    res: dict = {"thresholds": {k: getattr(S, k) for k in dir(S) if k.isupper()}}
    if a.realeval:
        res["realeval"] = realeval(Path(a.realeval))
    else:
        res["synthetic"] = synthetic(sorted(CORPUS.glob("syn-scan-*/gt.json")))
        if a.labels:
            res["labels"] = labels()
    text = json.dumps(res, ensure_ascii=False, indent=1, default=str)
    if a.out:
        Path(a.out).write_text(text + "\n", encoding="utf-8")
    print(text if a.realeval else json.dumps({k: v for k, v in res.items() if k != "thresholds"}, indent=1,
                                             default=str)[:6000])
    return 0


if __name__ == "__main__":
    sys.exit(main())
